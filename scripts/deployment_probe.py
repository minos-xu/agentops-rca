"""Two-phase real infrastructure probe without DeepSeek calls.

seed: use real API sessions, PostgreSQL checkpoints and Redis cache/limiter.
verify: read the same session/checkpoint after API and PostgreSQL restarts.
The graph checkpoint contains an explicitly synthetic deployment probe message.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
from pathlib import Path
import secrets
import sys
from urllib.parse import urlparse

import httpx
import psycopg
from psycopg.rows import dict_row


LOOPBACK = {"127.0.0.1", "localhost", "::1"}


class ProbeFailure(RuntimeError):
    """A deliberately credential-free diagnostic generated by this script."""


def configuration() -> tuple[str, str, str]:
    dsn = os.environ.get("POSTGRES_DSN", "").strip()
    redis_url = os.environ.get("REDIS_URL", "").strip()
    api_url = os.environ.get("AGENTOPS_API_URL", "http://127.0.0.1:8164").rstrip("/")
    for name, value, schemes in (
        ("POSTGRES_DSN", dsn, {"postgresql", "postgres"}),
        ("REDIS_URL", redis_url, {"redis"}),
        ("AGENTOPS_API_URL", api_url, {"http"}),
    ):
        try:
            parsed = urlparse(value)
            port = parsed.port
        except ValueError:
            raise ProbeFailure(f"{name} must be a valid loopback URL") from None
        if parsed.scheme not in schemes or parsed.hostname not in LOOPBACK:
            raise ProbeFailure(f"{name} must use an explicit loopback URL")
        if name == "POSTGRES_DSN" and port in (None, 5432, 55432):
            raise ProbeFailure("POSTGRES_DSN must target the isolated Lesson64 port, not the existing database")
        if name == "REDIS_URL" and port in (None, 6379, 56379):
            raise ProbeFailure("REDIS_URL must target the isolated Lesson64 port, not the existing Redis")
    return dsn, redis_url, api_url


def request(client: httpx.Client, method: str, path: str, *, status: int = 200) -> dict:
    response = client.request(method, path)
    if response.status_code != status:
        # Response bodies can contain session ids or upstream error details.
        raise ProbeFailure(f"API probe returned HTTP {response.status_code}; expected {status}")
    data = response.json()
    if not isinstance(data, dict):
        raise ProbeFailure("API probe returned a non-object response")
    return data


def health(client: httpx.Client) -> None:
    data = request(client, "GET", "/health")
    if data.get("status") != "ok" or data.get("dependencies", {}).get("redis") != "ok":
        raise ProbeFailure("API health probe is degraded")
    print("PASS: real FastAPI /health and Redis dependency", flush=True)


async def redis_probe(redis_url: str, run_id: str) -> None:
    from redis_store import Lesson57RedisStore
    store = Lesson57RedisStore(redis_url, prefix=f"agentops:lesson64:acceptance:{run_id}")
    try:
        assert await store.ping(), "Redis ping failed"
        value = {"kind": "synthetic-deployment-probe", "run_id": run_id}
        await store.set_json("probe", value, ttl_seconds=120)
        assert await store.get_json("probe") == value, "Redis cache roundtrip failed"
        ttl = await store.client.ttl(store._key("cache:probe"))
        assert 0 < ttl <= 120, "Redis cache TTL is missing"
        hits = await asyncio.gather(*(
            store.hit_rate_limit("probe", "concurrent", limit=3, window_seconds=120)
            for _ in range(12)
        ))
        assert sum(allowed for allowed, _, _ in hits) == 3, "Redis atomic limiter allowed an incorrect count"
        assert sorted(count for _, count, _ in hits) == list(range(1, 13)), "Redis Lua increments were not atomic"
        assert all(0 < retry <= 120 for _, _, retry in hits), "Redis limiter TTL is missing"
        print("PASS: real Redis JSON cache, TTL and concurrent Lua rate limit (3 of 12 allowed)", flush=True)
    finally:
        await store.delete_cache("probe")
        # Limiter probe keys expire naturally; no database flush or key scan.
        await store.close()


async def verify_api_case_cache(redis_url: str, expected: list) -> None:
    from redis_store import Lesson57RedisStore
    store = Lesson57RedisStore(redis_url)
    try:
        assert await store.get_json("cases:v1") == expected, "API catalogue is missing from its Redis cache"
        ttl = await store.client.ttl(store._key("cache:cases:v1"))
        assert ttl > 0, "API catalogue cache has no expiry"
    finally:
        await store.close()
    print("PASS: real API case catalogue matches the default-prefix Redis cache with a positive TTL", flush=True)


async def fill_message_quota(redis_url: str, session_id: str, limit: int, window: int) -> None:
    from redis_store import Lesson57RedisStore
    store = Lesson57RedisStore(redis_url)
    try:
        for expected in range(1, limit + 1):
            allowed, count, retry = await store.hit_rate_limit("messages", session_id, limit, window)
            assert allowed and count == expected and retry > 0, "Fresh probe session quota was not filled as expected"
    finally:
        await store.close()


async def verify_message_quota(redis_url: str, session_id: str, expected: int) -> None:
    from redis_store import Lesson57RedisStore
    store = Lesson57RedisStore(redis_url)
    try:
        key = store._key(f"rate:messages:{session_id}")
        count = await store.client.get(key)
        assert count is not None and int(count) == expected, "HTTP route did not increment the expected Redis limiter key"
        assert await store.client.ttl(key) > 0, "HTTP message limiter has no expiry"
    finally:
        await store.close()


def verify_http_message_limit(client: httpx.Client, redis_url: str, session_id: str) -> None:
    try:
        limit = int(os.environ.get("AGENTOPS_MESSAGE_RATE_LIMIT", "10"))
        window = int(os.environ.get("AGENTOPS_MESSAGE_RATE_WINDOW_SECONDS", "60"))
    except ValueError:
        raise ProbeFailure("Message limiter configuration must contain positive integers") from None
    if limit < 1 or window < 1:
        raise ProbeFailure("Message limiter configuration must contain positive integers")
    asyncio.run(fill_message_quota(redis_url, session_id, limit, window))
    response = client.post(
        f"/api/v1/sessions/{session_id}/messages",
        json={"message": "Lesson64 synthetic quota probe; reject this request before calling the LLM."},
    )
    if response.status_code != 429:
        raise ProbeFailure(f"Real HTTP message limiter returned {response.status_code}; expected 429")
    try:
        retry = int(response.headers.get("Retry-After", "0"))
    except ValueError:
        raise ProbeFailure("HTTP 429 Retry-After is not an integer") from None
    assert 0 < retry <= window, "HTTP 429 Retry-After is outside the configured window"
    asyncio.run(verify_message_quota(redis_url, session_id, limit + 1))
    print("PASS: real HTTP messages route returns 429 and valid Retry-After using the real Redis quota", flush=True)


async def thread_for_session(dsn: str, session_id: str) -> str:
    async with await psycopg.AsyncConnection.connect(dsn, autocommit=True, row_factory=dict_row) as conn:
        async with conn.cursor() as cur:
            await cur.execute("SELECT thread_id FROM agentops_sessions WHERE session_id=%s", (session_id,))
            row = await cur.fetchone()
    if row is None:
        raise ProbeFailure("API-created session is missing from PostgreSQL")
    return row["thread_id"]


async def seed_checkpoint(dsn: str, session_id: str, marker: str) -> dict:
    from langchain_core.messages import AIMessage
    from langgraph.checkpoint.postgres.aio import AsyncPostgresSaver
    from langgraph.graph import END, START, MessagesState, StateGraph
    thread_id = await thread_for_session(dsn, session_id)
    config = {"configurable": {"thread_id": thread_id}}
    builder = StateGraph(MessagesState)
    builder.add_node("deployment_probe", lambda state: {})
    builder.add_edge(START, "deployment_probe")
    builder.add_edge("deployment_probe", END)
    async with AsyncPostgresSaver.from_conn_string(dsn) as saver:
        # Existing app startup created the schema; no schema migration here.
        graph = builder.compile(checkpointer=saver)
        await graph.ainvoke({"messages": [AIMessage(content=marker)]}, config)
        checkpoint = await saver.aget_tuple(config)
        if checkpoint is None:
            raise ProbeFailure("PostgreSQL saver did not persist the probe checkpoint")
        checkpoint_id = checkpoint.config["configurable"]["checkpoint_id"]
    print("PASS: real PostgreSQL session mapping and synthetic AIMessage checkpoint", flush=True)
    return {"thread_id": thread_id, "checkpoint_id": checkpoint_id}


async def verify_checkpoint(dsn: str, state: dict) -> None:
    from langgraph.checkpoint.postgres.aio import AsyncPostgresSaver
    thread_id = await thread_for_session(dsn, state["session_id"])
    assert thread_id == state["thread_id"], "Session thread mapping changed"
    async with AsyncPostgresSaver.from_conn_string(dsn) as saver:
        saved = await saver.aget_tuple({"configurable": {"thread_id": thread_id}})
        assert saved is not None, "Checkpoint is missing"
        assert saved.config["configurable"]["checkpoint_id"] == state["checkpoint_id"], "Checkpoint id changed"
        messages = saved.checkpoint["channel_values"].get("messages", [])
        assert any(getattr(message, "content", None) == state["marker"] for message in messages), "Probe message is missing"
    print("PASS: identical session mapping, checkpoint id and message remain in PostgreSQL", flush=True)


def read_state(path: Path) -> dict:
    state = json.loads(path.read_text(encoding="utf-8"))
    if state.get("kind") != "lesson64-synthetic-deployment-probe":
        raise ProbeFailure("State file is not a Lesson64 deployment probe")
    for name in ("session_id", "thread_id", "checkpoint_id", "marker", "run_id"):
        if not isinstance(state.get(name), str) or not state[name]:
            raise ProbeFailure("State file has an invalid probe field")
    return state


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("phase", choices=("seed", "verify"))
    parser.add_argument("--state", type=Path, required=True, help="Private probe file retained across restarts")
    args = parser.parse_args()
    dsn, redis_url, api_url = configuration()
    # Setting the repo path allows execution from any working directory.
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    os.environ.setdefault("LANGGRAPH_STRICT_MSGPACK", "true")
    with httpx.Client(base_url=api_url, timeout=30, trust_env=False) as client:
        health(client)
        if args.phase == "seed":
            if args.state.exists():
                raise ProbeFailure("Probe file already exists; use verify, or select a new --state path")
            run_id = secrets.token_hex(12)
            asyncio.run(redis_probe(redis_url, run_id))
            cases_one = request(client, "GET", "/api/v1/cases")
            cases_two = request(client, "GET", "/api/v1/cases")
            assert cases_one == cases_two and cases_one.get("cases"), "API case cache response changed"
            asyncio.run(verify_api_case_cache(redis_url, cases_one["cases"]))
            created = request(client, "POST", "/api/v1/sessions", status=201)
            session_id = created["session_id"]
            assert created.get("durable") is True, "API session is not durable"
            request(client, "GET", f"/api/v1/sessions/{session_id}")
            verify_http_message_limit(client, redis_url, session_id)
            marker = f"Lesson64 synthetic persistence probe {run_id}; no LLM call."
            checkpoint = asyncio.run(seed_checkpoint(dsn, session_id, marker))
            state = {"kind": "lesson64-synthetic-deployment-probe", "run_id": run_id,
                     "session_id": session_id, "marker": marker, **checkpoint}
            args.state.parent.mkdir(parents=True, exist_ok=True)
            descriptor = os.open(args.state, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(descriptor, "w", encoding="utf-8") as output:
                json.dump(state, output, ensure_ascii=False, indent=2)
                output.write("\n")
        else:
            state = read_state(args.state)
        snapshot = request(client, "GET", f"/api/v1/sessions/{state['session_id']}")
        assert snapshot.get("answer") == state["marker"], "HTTP did not restore the probe message"
        asyncio.run(verify_checkpoint(dsn, state))
        print("PASS: real HTTP session read returns persisted checkpoint message", flush=True)
    print("No DeepSeek calls; checkpoint content is a synthetic deployment probe, not a production RCA result.", flush=True)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except ProbeFailure as error:
        # Only locally generated validation messages are printed. Never echo
        # DSNs, transport exceptions, API response bodies or session identifiers.
        print(f"FAIL: {error}", file=sys.stderr)
        raise SystemExit(1)
    except Exception as error:
        print(f"FAIL: {type(error).__name__}; inspect private service logs for details", file=sys.stderr)
        raise SystemExit(1)
